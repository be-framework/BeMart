<?php

declare(strict_types=1);

/**
 * bin/stats.php — reproducible scale metrics for the README "Evidence Snapshot".
 *
 * Every number is computed from the repository, so the snapshot never rots.
 * The shape is the hourglass: one ALPS contract (the waist) fanned out into
 * the Be domain, BEAR resources, SQL, schema and HTML, all verified.
 *
 *   php bin/stats.php           print the generated block to stdout
 *   php bin/stats.php --write   replace the <!-- stats:* --> region in README.md
 */

$root = dirname(__DIR__);

/** @return list<string> */
function rglob(string $dir, string $ext): array
{
    if (! is_dir($dir)) {
        return [];
    }

    $out = [];
    $it = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
    );
    foreach ($it as $f) {
        if ($f->isFile() && $f->getExtension() === $ext) {
            $out[] = $f->getPathname();
        }
    }

    return $out;
}

$nfiles = static fn (string $glob): int => count(glob($glob) ?: []);

// --- 契約（くびれ）: ALPS ---
$alps = json_decode((string) file_get_contents("$root/alps.json"), true);
$desc = $alps['alps']['descriptor'] ?? $alps['descriptor'] ?? [];
$nDesc = count($desc);
$nTrans = 0;
foreach ($desc as $d) {
    if (in_array($d['type'] ?? 'semantic', ['safe', 'unsafe', 'idempotent'], true)) {
        $nTrans++;
    }
}

// --- ドメイン層（Be）---
$beIn = $nfiles("$root/be/src/Input/*.php");
$beFi = $nfiles("$root/be/src/Final/*.php");
$beSe = $nfiles("$root/be/src/Semantic/*.php");
$beRe = count(rglob("$root/be/src/Reason", 'php'));
$beBe = $nfiles("$root/be/src/Being/*.php");

// --- 実装（出口）---
$res = count(rglob("$root/src/Resource", 'php'));
$sql = $nfiles("$root/var/sql/*.sql");
$schema = $nfiles("$root/var/json_schema/*.json");
$twig = count(rglob("$root/var/templates", 'twig'));
$dbq = 0;
foreach ([...rglob("$root/src", 'php'), ...rglob("$root/be/src", 'php')] as $f) {
    $dbq += substr_count((string) file_get_contents($f), '#[DbQuery');
}

// --- 検証 ---
$tm = 0;
foreach ([...rglob("$root/tests", 'php'), ...rglob("$root/be/tests", 'php')] as $f) {
    $tm += preg_match_all('/function\s+test[A-Z0-9]/', (string) file_get_contents($f));
}
$items = json_decode((string) file_get_contents("$root/docs/eccube-spec-coverage/all_items.json"), true);
$nItems = count($items);
$areas = count(array_unique(array_map(static fn ($x) => $x['area'], $items)));

$pad = static fn (string $s, int $w): string => $s . str_repeat(' ', max(0, $w - mb_strwidth($s)));
$row = static fn (string $label, int|string $num, string $note): string => '   ' . $pad($label, 25) . sprintf('%4s', (string) $num) . ($note === '' ? '' : '   ' . $note);

$hourglass = implode("\n", [
    '            ALPS profile ×1   ← 契約（くびれ / source of truth）',
    "            {$nDesc} descriptor / {$nTrans} transition",
    '                  │  ↓ 契約の実装が fan-out',
    $row('ドメイン入力 (Be Input)', $beIn, '操作の起点（doXxx の意図）'),
    $row('ドメイン出力 (Be Final)', $beFi, '確定状態（＝完了の証明）'),
    $row('意味語彙 (Be Semantic)', $beSe, '制約付き値オブジェクト'),
    $row('ドメイン作用 (Be Reason)', $beRe, '注入される問い合わせ／コマンド'),
    $row('中間状態 (Be Being)', $beBe, 'becoming の途中相'),
    '   ───────────────',
    $row('HTTP リソース (BEAR)', $res, ''),
    '   ' . $pad('永続化 (SQL)', 25) . sprintf('%4s', (string) $sql) . " file / {$dbq} #[DbQuery]",
    $row('入出力契約 (JSON Schema)', $schema, ''),
    $row('HTML (Twig)', $twig, ''),
    '   ───────────────',
    "   検証  PHPUnit {$tm} test methods（全スイート緑）",
    "        結合試験 {$nItems}項目 / {$areas}領域 → docs/eccube-spec-coverage/implementation-status.html",
]);

$block = "<!-- stats:start (generated by bin/stats.php — do not edit by hand) -->\n"
    . "最新の規模はリポジトリから自動算出（`composer stats`）。すべて **1 つの ALPS 契約** から fan-out している。\n\n"
    . "```text\n{$hourglass}\n```\n"
    . "<!-- stats:end -->";

$readme = "$root/README.md";
if (in_array('--write', $argv, true)) {
    $md = (string) file_get_contents($readme);
    $new = preg_replace('/<!-- stats:start.*?<!-- stats:end -->/s', $block, $md, 1, $count);
    if ($count !== 1) {
        fwrite(STDERR, "ERROR: stats markers not found in README.md (add <!-- stats:start --> / <!-- stats:end -->)\n");
        exit(1);
    }

    file_put_contents($readme, $new);
    echo "README.md updated.\n";
} else {
    echo $block, "\n";
}
